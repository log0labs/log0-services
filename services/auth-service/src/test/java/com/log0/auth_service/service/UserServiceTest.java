package com.log0.auth_service.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.util.Optional;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import com.log0.auth_service.entity.User;
import com.log0.auth_service.entity.User.Role;
import com.log0.auth_service.exception.OperationNotAllowedException;
import com.log0.auth_service.exception.ResourceNotFoundException;
import com.log0.auth_service.repository.RefreshTokenRepository;
import com.log0.auth_service.repository.TenantRepository;
import com.log0.auth_service.repository.UserRepository;

import org.springframework.security.crypto.password.PasswordEncoder;

/**
 * The rules that stop a workspace from locking itself out: no self changes, no removing
 * the last admin, and no reaching a user in another tenant.
 */
@ExtendWith(MockitoExtension.class)
class UserServiceTest {

    @Mock
    private UserRepository userRepository;
    @Mock
    private TenantRepository tenantRepository;
    @Mock
    private RefreshTokenRepository refreshTokenRepository;
    @Mock
    private PasswordEncoder passwordEncoder;
    @InjectMocks
    private UserService service;

    private final UUID tenantId = UUID.randomUUID();
    private final UUID actorId = UUID.randomUUID();
    private final UUID targetId = UUID.randomUUID();
    private User target;

    @BeforeEach
    void setUp() {
        target = new User();
        target.setRole(Role.ENGINEER);
        // the id is generated by JPA on save, so a unit test sets it directly
        setId(target, targetId);
    }

    private static void setId(User user, UUID id) {
        try {
            var field = User.class.getDeclaredField("userId");
            field.setAccessible(true);
            field.set(user, id);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }

    @Test
    void changesARoleAndSignsTheUserOut() {
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.of(target));

        var result = service.updateRole(tenantId, actorId, targetId, Role.VIEWER);

        assertEquals(Role.VIEWER, result.getRole());
        verify(userRepository).save(target);
        verify(refreshTokenRepository).revokeAllByUserId(targetId);
    }

    @Test
    void cannotChangeYourOwnRole() {
        setId(target, actorId);
        when(userRepository.findByUserIdAndTenantTenantId(actorId, tenantId)).thenReturn(Optional.of(target));

        assertThrows(OperationNotAllowedException.class,
                () -> service.updateRole(tenantId, actorId, actorId, Role.ADMIN));
        verify(userRepository, never()).save(any());
    }

    @Test
    void cannotDemoteTheLastAdmin() {
        target.setRole(Role.ADMIN);
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.of(target));
        when(userRepository.countByTenantTenantIdAndRole(tenantId, Role.ADMIN)).thenReturn(1L);

        assertThrows(OperationNotAllowedException.class,
                () -> service.updateRole(tenantId, actorId, targetId, Role.VIEWER));
        verify(userRepository, never()).save(any());
    }

    @Test
    void canDemoteAnAdminWhenAnotherRemains() {
        target.setRole(Role.ADMIN);
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.of(target));
        when(userRepository.countByTenantTenantIdAndRole(tenantId, Role.ADMIN)).thenReturn(2L);

        assertEquals(Role.ENGINEER, service.updateRole(tenantId, actorId, targetId, Role.ENGINEER).getRole());
    }

    @Test
    void aUserInAnotherTenantIsNotFound() {
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.empty());

        assertThrows(ResourceNotFoundException.class,
                () -> service.updateRole(tenantId, actorId, targetId, Role.VIEWER));
        assertThrows(ResourceNotFoundException.class, () -> service.deleteUser(tenantId, actorId, targetId));
    }

    @Test
    void deletesAUserAndTheirSessions() {
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.of(target));

        service.deleteUser(tenantId, actorId, targetId);

        verify(refreshTokenRepository).deleteAllByUserId(targetId);
        verify(userRepository).delete(target);
    }

    @Test
    void cannotDeleteYourselfOrTheLastAdmin() {
        setId(target, actorId);
        when(userRepository.findByUserIdAndTenantTenantId(actorId, tenantId)).thenReturn(Optional.of(target));
        assertThrows(OperationNotAllowedException.class, () -> service.deleteUser(tenantId, actorId, actorId));

        User admin = new User();
        admin.setRole(Role.ADMIN);
        setId(admin, targetId);
        when(userRepository.findByUserIdAndTenantTenantId(targetId, tenantId)).thenReturn(Optional.of(admin));
        when(userRepository.countByTenantTenantIdAndRole(tenantId, Role.ADMIN)).thenReturn(1L);
        assertThrows(OperationNotAllowedException.class, () -> service.deleteUser(tenantId, actorId, targetId));
        verify(userRepository, never()).delete(any());
    }
}
